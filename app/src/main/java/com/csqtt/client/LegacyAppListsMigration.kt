package com.csqtt.client

/** Пара локальных списков приложений одного профиля. */
internal data class ProfileAppLists(
    val black: String,
    val white: String,
)

/**
 * Перенос легаси-настройки с одним списком на два ключа.
 *
 * До разделения режимов список приложений лежал в одном ключе
 * (`EXCLUDED_APPS`) независимо от режима: в белом режиме там был белый список.
 * Новая настройка читает только список того режима, который задаёт правило,
 * поэтому старый список переезжает в свою ветку, а противоположная остаётся
 * пустой.
 *
 * Синтезировать «всё установленное минус старый список» нельзя: под чёрным
 * правилом такая ветка прочиталась бы как настоящий чёрный список и увела бы
 * мимо тоннеля почти всё устройство — тот же переворот списка, только в данных.
 */
internal object LegacyAppListsMigration {
    fun fromLegacyWhiteList(legacyList: String?): ProfileAppLists = ProfileAppLists(
        black = "",
        white = legacyList.orEmpty(),
    )

    /**
     * Чем заменить чёрную ветку профиля при одноразовом ремонте.
     *
     * В белом режиме ветка очищается: непустое значение там — синтез прежней
     * миграции («всё установленное минус белый список»), а не выбор пользователя.
     * В чёрном режиме список пользовательский, поэтому возвращается как есть
     * (null означает «не трогать ключ»).
     *
     * [black] — текущее значение ветки: пустая ветка чинить нечего, и ремонт
     * возвращает null («не трогать»), чтобы идемпотентный повторный проход не
     * переписывал ключ заново.
     */
    fun repairedBlacklist(isWhitelist: Boolean, black: String?): String? =
        if (!isWhitelist || black.isNullOrEmpty()) null else ""
}
